import {
  AlignLeft,
  ArrowDownToLine,
  Bold,
  ChevronDown,
  Copy,
  Expand,
  Italic,
  LoaderCircle,
  Mail,
  Minus,
  Plus,
  Sparkles,
  WandSparkles,
} from "lucide-react";
import { useEffect, useState } from "react";
import { useNavigate } from "react-router-dom";
import { Button, Card, DemoNotice, PageHeading } from "../components/ui";
import {
  beginGmailComposeConnect,
  createGmailDraft,
  getGmailStatus,
  rewriteEmail,
  writeEmail,
} from "../services/api";
import type { AITone, GmailStatus } from "../types/api";

type WritingAction = "generate" | "rewrite" | "improve" | "shorten" | "expand";
type Tone = AITone;

const actionLabels: Record<WritingAction, string> = {
  generate: "Generate draft",
  rewrite: "Rewrite",
  improve: "Improve clarity",
  shorten: "Shorten",
  expand: "Expand",
};

const tones: Tone[] = [
  "Professional",
  "Friendly",
  "Formal",
  "Concise",
  "Persuasive",
  "Appreciative",
];

export default function WritingStudioPage() {
  const navigate = useNavigate();
  const [to, setTo] = useState("");
  const [subject, setSubject] = useState("");
  const [instructions, setInstructions] = useState("");
  const [content, setContent] = useState("");
  const [tone, setTone] = useState<Tone>("Professional");
  const [loading, setLoading] = useState(false);
  const [error, setError] = useState("");
  const [notice, setNotice] = useState("");
  const [subjectSuggestions, setSubjectSuggestions] = useState<string[]>([]);
  const [gmailStatus, setGmailStatus] = useState<GmailStatus | null>(null);
  const [gmailStatusLoading, setGmailStatusLoading] = useState(true);
  const [gmailDraftSaving, setGmailDraftSaving] = useState(false);
  const [gmailDraftSaved, setGmailDraftSaved] = useState(false);

  useEffect(() => {
    let active = true;
    getGmailStatus()
      .then((result) => {
        if (active) setGmailStatus(result);
      })
      .catch(() => {
        if (active) setGmailStatus(null);
      })
      .finally(() => {
        if (active) setGmailStatusLoading(false);
      });
    return () => {
      active = false;
    };
  }, []);

  async function generate(action: "generate" | "subject_lines" = "generate") {
    if (!instructions.trim()) {
      setError("Describe what the email should say before generating a draft.");
      return;
    }
    setLoading(true);
    setError("");
    setNotice("");
    try {
      const result = await writeEmail({
        action,
        instructions: instructions.trim(),
        recipient: to.trim() || undefined,
        subject: subject.trim() || undefined,
        body: content.trim() || undefined,
        tone,
      });
      if (action === "subject_lines") {
        setSubjectSuggestions(result.subject_suggestions);
        setNotice("Subject suggestions generated by Gemini. Review before use.");
      } else {
        setSubject(result.subject || subject);
        setContent(result.body);
        setSubjectSuggestions(result.subject_suggestions);
        setNotice("Gemini draft suggestion ready. Review and edit before using.");
      }
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : "Gemini could not generate a draft.");
    } finally {
      setLoading(false);
    }
  }

  async function rewrite(action: Exclude<WritingAction, "generate">) {
    if (!content.trim()) {
      setError("Add draft text before asking Gemini to revise it.");
      return;
    }
    setLoading(true);
    setError("");
    setNotice("");
    try {
      const result = await rewriteEmail({
        action,
        content,
        tone,
        instructions: instructions.trim() || undefined,
      });
      setContent(result.content);
      setNotice("Gemini revision ready. Review and edit before using.");
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : "Gemini could not revise this draft.");
    } finally {
      setLoading(false);
    }
  }

  async function copyDraft() {
    if (!content) return;
    try {
      await navigator.clipboard.writeText(content);
      setNotice("Draft copied to clipboard.");
      setError("");
    } catch {
      setError("Clipboard access is unavailable in this browser.");
    }
  }

  async function saveToGmailDrafts() {
    const recipients = to.split(",").map((address) => address.trim()).filter(Boolean);
    if (!recipients.length) {
      setError("Add at least one recipient before saving to Gmail.");
      return;
    }
    if (!content.trim()) {
      setError("Generate or write a message before saving to Gmail.");
      return;
    }
    if (!gmailStatus?.connected || gmailStatus.requires_reconnect) {
      setError("");
      setNotice("Connect or reconnect Gmail in Settings before saving a real draft.");
      navigate("/settings");
      return;
    }
    if (!gmailStatus.compose_enabled) {
      setGmailDraftSaving(true);
      setError("");
      try {
        await beginGmailComposeConnect();
      } catch (reason) {
        setError(reason instanceof Error ? reason.message : "Gmail draft permission could not be enabled.");
        setGmailDraftSaving(false);
      }
      return;
    }

    setGmailDraftSaving(true);
    setError("");
    setNotice("");
    setGmailDraftSaved(false);
    try {
      await createGmailDraft({
        recipients,
        cc: [],
        bcc: [],
        subject,
        body: content,
      });
      setGmailDraftSaved(true);
      setNotice("Draft saved to Gmail. It has not been sent.");
    } catch (reason) {
      setError(reason instanceof Error ? reason.message : "Gmail could not confirm the draft save.");
    } finally {
      setGmailDraftSaving(false);
    }
  }

  function clearDraft() {
    setContent("");
    setSubjectSuggestions([]);
    setNotice("");
    setError("");
    setGmailDraftSaved(false);
  }

  return (
    <div>
      <PageHeading
        eyebrow="Writing studio"
        title="Words, made a little easier."
        description="Create an editable draft suggestion with Gemini."
        action={<DemoNotice>Gemini · draft suggestions only</DemoNotice>}
      />
      <div className="grid gap-5 xl:grid-cols-[minmax(0,1.55fr)_minmax(280px,0.7fr)]">
        <Card className="overflow-hidden">
          <div className="flex flex-wrap items-center justify-between gap-3 border-b border-line px-5 py-4">
            <div className="flex items-center gap-2">
              <span className="grid size-8 place-items-center rounded-lg bg-accent/10 text-accent"><Mail size={15} /></span>
              <div><h2 className="text-sm font-semibold">New message</h2><p className="text-[10px] text-muted">Generated content stays an editable suggestion</p></div>
            </div>
            <label className="flex items-center gap-2 text-[11px] text-muted">Tone
              <select aria-label="Tone" value={tone} onChange={(event) => setTone(event.target.value as Tone)} className="input h-8 rounded-lg px-2 text-xs">
                {tones.map((value) => <option key={value}>{value}</option>)}
              </select>
            </label>
          </div>
          <div className="divide-y divide-line">
            <label className="flex items-center gap-3 px-5 py-3 text-xs"><span className="w-14 text-muted">To</span><input value={to} onChange={(event) => setTo(event.target.value)} placeholder="name@example.test" className="w-full bg-transparent text-subtle outline-none placeholder:text-faint" /></label>
            <label className="flex items-center gap-3 px-5 py-3 text-xs"><span className="w-14 text-muted">Subject</span><input value={subject} onChange={(event) => setSubject(event.target.value)} placeholder="Optional subject" className="w-full bg-transparent text-subtle outline-none placeholder:text-faint" /></label>
          </div>
          <label className="block border-b border-line px-5 py-3 text-xs">
            <span className="mb-2 block text-muted">What should the email say?</span>
            <textarea value={instructions} onChange={(event) => setInstructions(event.target.value)} placeholder="Describe the purpose and the facts to include. Avoid adding information you do not want in the draft." rows={3} className="w-full resize-y bg-transparent leading-5 text-subtle outline-none placeholder:text-faint" />
          </label>
          <div className="flex items-center gap-1 border-b border-line px-4 py-2"><button aria-label="Bold" className="format-button"><Bold size={14} /></button><button aria-label="Italic" className="format-button"><Italic size={14} /></button><span className="mx-1 h-4 w-px bg-line" /><button aria-label="Decrease indent" className="format-button"><Minus size={14} /></button><button aria-label="Increase indent" className="format-button"><Plus size={14} /></button><button aria-label="Formatting options" className="format-button"><AlignLeft size={14} /></button><span className="ml-auto text-[10px] text-muted">Plain text</span></div>
          <label className="block">
            <span className="sr-only">Draft content</span>
            <textarea value={content} onChange={(event) => setContent(event.target.value)} placeholder="Your editable draft suggestion will appear here…" className="min-h-[240px] w-full resize-y bg-transparent px-5 py-4 text-sm leading-7 text-subtle outline-none placeholder:text-faint" />
          </label>
          {loading && <div role="status" className="mx-5 mb-3 flex items-center gap-2 rounded-lg bg-accent/5 px-3 py-2 text-xs text-accent"><LoaderCircle size={14} className="animate-spin" />Waiting for Gemini…</div>}
          {error && <p role="alert" className="mx-5 mb-3 text-[11px] text-rose-600">{error}</p>}
          {notice && <p role="status" className="mx-5 mb-3 text-[11px] text-accent">{notice}</p>}
          <div className="flex flex-wrap items-center justify-between gap-3 border-t border-line px-5 py-4">
            <span className="text-[10px] text-muted">{content.length} characters · Not sent</span>
            <div className="flex flex-wrap gap-2">
              <Button onClick={() => void rewrite("rewrite")} disabled={loading}><WandSparkles size={14} /> Rewrite</Button>
              <Button onClick={() => void rewrite("shorten")} disabled={loading}>Shorten</Button>
              <Button variant="primary" onClick={() => void generate()} disabled={loading}>{loading ? <LoaderCircle size={14} className="animate-spin" /> : <Sparkles size={14} />}Generate draft</Button>
            </div>
          </div>
        </Card>
        <div className="space-y-5">
          <Card className="p-5">
            <div className="flex items-center gap-2"><Sparkles size={15} className="text-accent" /><h2 className="text-sm font-semibold">Writing actions</h2></div>
            <p className="mt-1 text-xs leading-5 text-muted">Gemini uses the text you submit to make a suggestion; review every result.</p>
            <div className="mt-4 space-y-2">{(["improve", "shorten", "expand"] as const).map((action) => <button key={action} onClick={() => void rewrite(action)} disabled={loading} className="flex w-full items-center justify-between rounded-xl border border-line px-3 py-3 text-left text-xs transition hover:bg-soft disabled:opacity-50"><span className="flex items-center gap-2"><WandSparkles size={14} className="text-accent" />{actionLabels[action]}</span><ChevronDown size={13} className="rotate-[-90deg] text-muted" /></button>)}</div>
            <Button className="mt-3 w-full justify-center" onClick={() => void generate("subject_lines")} disabled={loading || !instructions.trim()}>Suggest subject lines</Button>
            {subjectSuggestions.length > 0 && <div className="mt-3 space-y-2" aria-label="Subject suggestions">{subjectSuggestions.map((suggestion) => <button key={suggestion} className="block w-full rounded-lg border border-line p-2 text-left text-xs text-subtle hover:bg-soft" onClick={() => setSubject(suggestion)}>{suggestion}</button>)}</div>}
          </Card>
          <Card className="p-5"><h2 className="text-sm font-semibold">Draft tools</h2><div className="mt-3 space-y-2"><Button className="w-full justify-center" onClick={() => void copyDraft()} disabled={!content}><Copy size={14} /> Copy draft</Button><Button className="w-full justify-center" onClick={clearDraft}><ArrowDownToLine size={14} /> Clear editor</Button><Button className="w-full justify-center" onClick={() => void saveToGmailDrafts()} disabled={gmailDraftSaving || gmailStatusLoading || !content}><Mail size={14} />{gmailDraftSaving ? "Saving…" : gmailStatus?.compose_enabled ? "Save to Gmail Drafts" : gmailStatus?.connected ? "Enable Gmail draft access" : "Connect Gmail in Settings"}</Button>{gmailDraftSaved && <Button className="w-full justify-center" onClick={() => navigate("/drafts")}>Open Gmail Drafts</Button>}</div></Card>
          <div className="rounded-xl border border-dashed border-line p-4 text-xs leading-5 text-muted"><Expand size={14} className="mb-2 text-faint" />Gemini-generated text is a draft suggestion, not an email action. Your writing is sent to Google's Gemini API when you request generation or revision.</div>
        </div>
      </div>
    </div>
  );
}
